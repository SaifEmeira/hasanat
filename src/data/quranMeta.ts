export function toArabicIndic(num: number): string {
  const digits = ['٠', '١', '٢', '٣', '٤', '٥', '٦', '٧', '٨', '٩'];
  return String(num)
    .split('')
    .map((ch) => digits[Number(ch)] ?? ch)
    .join('');
}

export function globalAyahToSurahAyah(globalAyah: number): {
  surahNumber: number;
  ayahNumber: number;
  page: number;
} {
  let remaining = Math.max(1, Math.min(6236, globalAyah));
  for (const s of SURAH_LIST) {
    if (remaining <= s.ayahCount) {
      return {surahNumber: s.number, ayahNumber: remaining, page: s.startPage};
    }
    remaining -= s.ayahCount;
  }
  return {surahNumber: 114, ayahNumber: 6, page: 604};
}

export function getAyahAudioUrl(
  everyAyahFolder: string,
  globalAyahNumber: number,
  surahNumber?: number,
  ayahInSurah?: number
): string {
  const resolved =
    surahNumber && ayahInSurah
      ? {surahNumber, ayahNumber: ayahInSurah}
      : globalAyahToSurahAyah(globalAyahNumber);
  const sss = String(resolved.surahNumber).padStart(3, '0');
  const aaa = String(resolved.ayahNumber).padStart(3, '0');
  return `https://everyayah.com/data/${everyAyahFolder}/${sss}${aaa}.mp3`;
}
